/**
 * compute-markings — regenerate the precomputed marking table.
 *
 * A thin runner: for every stored triangulation, derive its combinatorics and run the
 * core `canonicalMarking` (the expensive harmonic-layout + exact-min-cut pass), then write
 * the results to `src/core/triangulations/markings.generated.ts` keyed by id. All the math
 * lives in core; this just calls it and serializes the result.
 *
 * Run `npm run compute-markings` after adding or changing triangulation data.
 */

import { writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, resolve } from 'path';
import { deriveCombinatorics } from '@core/topology/triangulation.ts';
import { canonicalMarking } from '@core/topology/marking.ts';
import { EIGHT_VERTEX } from '@core/triangulations/eightVertex.ts';

const DATA = [...EIGHT_VERTEX];   // …add NINE_VERTEX here once it lands

const OUT = resolve(dirname(fileURLToPath(import.meta.url)), '../src/core/triangulations/markings.generated.ts');

const body = DATA.map((d) => {
  const marking = canonicalMarking(deriveCombinatorics(d.triangles));
  const loops = JSON.stringify(marking.loops);
  const cut = JSON.stringify(marking.cut);
  const developOrder = JSON.stringify(marking.developOrder);
  return `  '${d.id}': {\n    loops: ${loops},\n    cut: ${cut},\n    developOrder: ${developOrder},\n  },`;
}).join('\n');

const file = `/**
 * GENERATED by scripts/compute-markings.mjs — DO NOT EDIT BY HAND.
 *
 * The precomputed marking (developing chart) of each triangulation, keyed by id, in
 * readable vertex/edge/face numbers. A marking is a deterministic function of the triangle
 * list; this file is that function tabulated over the stored triangulations. Regenerate
 * with \`npm run compute-markings\` after changing triangulation data.
 */

import type { Marking } from '@core/topology/triangulation.ts';

export const MARKINGS: Record<string, Marking> = {
${body}
};
`;

writeFileSync(OUT, file);
process.stderr.write(`compute-markings: wrote ${DATA.length} markings → ${OUT}\n`);
