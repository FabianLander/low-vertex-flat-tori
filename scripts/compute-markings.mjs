/**
 * compute-markings — regenerate the precomputed marking tables, one file per census.
 *
 * A thin runner: for every stored triangulation, derive its combinatorics and run the
 * core `canonicalMarking` (the expensive harmonic-layout + exact-min-cut pass), then write
 * the results to `<census>.markings.generated.ts` keyed by id (e.g.
 * `eightVertex.markings.generated.ts`), 1:1 with the data files. All the math lives in core;
 * this just calls it and serializes the result.
 *
 * Run `npm run compute-markings` after adding or changing triangulation data.
 */

import { writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, resolve } from 'path';
import { deriveCombinatorics } from '@core/topology/triangulation.ts';
import { canonicalMarking } from '@core/topology/marking.ts';
import { SEVEN_VERTEX } from '@core/triangulations/sevenVertex.ts';
import { EIGHT_VERTEX } from '@core/triangulations/eightVertex.ts';
import { NINE_VERTEX } from '@core/triangulations/nineVertex.ts';
import { TEN_VERTEX } from '@core/triangulations/tenVertex.ts';

// one marking file per census, named to pair with the data file
const CENSUSES = [
  { data: SEVEN_VERTEX, out: 'sevenVertex.markings.generated.ts' },
  { data: EIGHT_VERTEX, out: 'eightVertex.markings.generated.ts' },
  { data: NINE_VERTEX,  out: 'nineVertex.markings.generated.ts' },
  { data: TEN_VERTEX,   out: 'tenVertex.markings.generated.ts' },
];

const DIR = resolve(dirname(fileURLToPath(import.meta.url)), '../src/core/triangulations');

for (const { data, out } of CENSUSES) {
  const t0 = performance.now();
  const body = data.map((d) => {
    const m = canonicalMarking(deriveCombinatorics(d.triangles));
    return `  '${d.id}': { loops: ${JSON.stringify(m.loops)}, cut: ${JSON.stringify(m.cut)}, developOrder: ${JSON.stringify(m.developOrder)} },`;
  }).join('\n');
  const file = `/**
 * GENERATED by scripts/compute-markings.mjs — DO NOT EDIT BY HAND.
 *
 * The precomputed marking (developing chart) of each triangulation in ${out.replace('.markings.generated.ts', '.ts')},
 * keyed by id, in readable vertex/edge/face numbers. A marking is a deterministic function of
 * the triangle list; this file is that function tabulated over the census. Regenerate with
 * \`npm run compute-markings\` after changing triangulation data.
 */

import type { Marking } from '@core/topology/triangulation.ts';

export const MARKINGS: Record<string, Marking> = {
${body}
};
`;
  writeFileSync(resolve(DIR, out), file);
  process.stderr.write(`compute-markings: ${out} — ${data.length} markings in ${((performance.now() - t0) / 1000).toFixed(1)}s\n`);
}
