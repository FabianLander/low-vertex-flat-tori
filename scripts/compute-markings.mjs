/**
 * compute-markings — compute each triangulation's canonical marking (the
 * minimal-domain developOrder + cut-aligned H₁ generators) and write them to
 * src/tori/markings.ts. This is the one expensive derivation worth saving (the
 * min-cut search is exponential in edge count); everything else recomputes
 * cheaply on load. The marking is deterministic, so the saved file is identical
 * to recomputing — it's a pure optimization.
 *
 * Run this whenever you add or change a triangulation:
 *   npm run compute-markings
 *
 * defineTriangulation reads this cache (markings.ts) to decorate each
 * triangulation with its marking — all seven, including #7. If a triangulation
 * has no saved entry, it falls back to a layout-free marking, so the build
 * always works even before this runs.
 */

import { writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, resolve } from 'path';

import { ALL_TORI } from '../src/tori/index.ts';
import { canonicalDecoration } from '../src/math/marking.ts';

const outPath = resolve(dirname(fileURLToPath(import.meta.url)), '../src/tori/markings.ts');

const rows = ALL_TORI.map((torus) => {
  const t0 = performance.now();
  const { developOrder, generatorLoops, cut } = canonicalDecoration(torus);
  const ms = (performance.now() - t0).toFixed(0);
  const loops = generatorLoops.map((l) => `[${l.join(', ')}]`).join(', ');
  console.log(`#${torus.id} ${torus.name}: developOrder len ${developOrder.length}, ${generatorLoops.length} generators, cut ${cut.length}  (${ms}ms)`);
  return `  ${torus.id}: { developOrder: [${developOrder.join(', ')}], generatorLoops: [${loops}], cut: [${cut.join(', ')}] },`;
});

const body = `// AUTO-GENERATED by \`npm run compute-markings\` — do not edit by hand.
// The canonical minimal-domain marking (cut + developOrder + generatorLoops) per
// triangulation id, read by defineTriangulation. Absent ids fall back to a
// layout-free marking. See src/math/marking.ts.

export type SavedMarking = { developOrder: number[]; generatorLoops: number[][]; cut: number[] };

export const MARKINGS: Record<number, SavedMarking> = {
${rows.join('\n')}
};
`;

writeFileSync(outPath, body);
console.log(`\nwrote ${outPath}`);
